"""Synthetic catalog entries: data CAMBER generates locally instead of downloading (0.103, #133).

Some faults no open dataset shows -- a boiler left enabled through a warm spell, a hot-water pump
left running all summer -- so a learner never sees the rule that looks for them fire. A catalog
entry of ``kind: "synthetic"`` fills that gap through the normal lab and workbook flow: its
"fetch" runs one of CAMBER's own generators (:data:`GENERATORS`) into the cache's ``downloads/``
directory, deterministically (a fixed seed and integer-only noise, so every copy writes the same
bytes), and from there it is ingested like any other entry into a ``ds-<id>`` facility.

What differs from a downloaded entry:

* nothing is downloaded: the entry's files carry no URL, size or sha256 (the generator *is* the
  pin: its name, version and seed are part of the entry and of the manifest record);
* the licence is CAMBER's own (Apache-2.0): the data is generated by the user's copy of CAMBER,
  carries no third party's terms, and may be redistributed;
* it is labelled synthetic everywhere a learner meets it -- the catalog page, ``camber datasets
  list`` / ``info``, the report's "Data source & licence" block (``synthetic: true`` in the
  provenance) and the docs -- because it describes no real building;
* ``scripts/datasets_refresh.py`` and ``scripts/datasets_linkcheck.py`` skip it (no URL to check).

:func:`camber.datasets._catalog.validate_catalog` still validates the entry: a known generator,
its file names, no download fields, the CAMBER licence and an open tier.
"""

from __future__ import annotations

import os
from collections.abc import Callable
from dataclasses import dataclass

import numpy as np
import pandas as pd

from .. import __version__
from . import _paths

#: The licence of every synthetic entry: CAMBER's own (the data is generated by the user's copy).
SYNTHETIC_LICENCE = "Apache-2.0"


@dataclass(frozen=True)
class Generator:
    """One synthetic data generator: the files it writes and how (``build(seed) -> {name:
    text}``). ``version`` changes whenever the bytes it writes change."""

    version: int
    files: tuple
    build: Callable[[int], dict]
    description: str = ""


# --------------------------------------------------------------------------- deterministic noise


def _noise(n: int, seed: int, stream: int) -> np.ndarray:
    """``n`` uniform values in [0, 1) from a 64-bit integer hash (splitmix64) of
    ``(seed, stream, i)`` -- integer arithmetic only, so every platform and numpy version gives
    the same values."""
    with np.errstate(over="ignore"):
        x = np.arange(n, dtype=np.uint64) + np.uint64(seed * 1_000_003 + stream * 7_919)
        x = x * np.uint64(0x9E3779B97F4A7C15)
        x = (x ^ (x >> np.uint64(30))) * np.uint64(0xBF58476D1CE4E5B9)
        x = (x ^ (x >> np.uint64(27))) * np.uint64(0x94D049BB133111EB)
        x = x ^ (x >> np.uint64(31))
    return (x >> np.uint64(11)).astype(np.float64) / float(1 << 53)


def _smooth(u: np.ndarray, width: int) -> np.ndarray:
    """A centred moving average of ``u`` (``width`` samples), edge-padded, scaled to about -1..1."""
    k = np.ones(width) / width
    pad = np.pad(u - 0.5, (width // 2, width - width // 2 - 1), mode="edge")
    out = np.convolve(pad, k, mode="valid")
    return out / max(float(np.abs(out).max()), 1e-9)


# ------------------------------------------------------------------- hot-water plant lockout

#: The four plants of the ``hw_plant_lockout`` generator: scenario -> (lockout °F, boiler left
#: enabled through the warm spell, pump left running).
_LOCKOUT_PLANTS = {
    "locked_out": (65.0, False, False),
    "warm_spell": (65.0, True, False),
    "pump_left_on": (65.0, False, True),
    "low_lockout": (58.0, False, False),
}
#: The warm spell (days from the start) every plant sees in its weather.
_SPELL = (22, 32)
_START = "2025-05-05"  # a Monday
_DAYS = 56
_DEADBAND_F = 3.0  # the plant re-enables this far below its lockout
_BALANCE_F = 55.0  # below this outdoor temperature the building needs heat


def _lockout_weather(seed: int) -> tuple:
    idx = pd.date_range(_START, periods=_DAYS * 24, freq="1h")
    n = len(idx)
    day = np.arange(n) / 24.0
    hour = np.asarray(idx.hour, dtype=float)
    season = 56.0 + 14.0 * day / _DAYS  # mid-50s in early May to about 70 F by late June
    diurnal = 9.0 * np.sin((hour - 9.0) / 24.0 * 2.0 * np.pi)  # warmest mid-afternoon
    swing = 5.0 * _smooth(_noise(n, seed, 1), 24 * 4)  # multi-day weather systems
    spell = np.where((day >= _SPELL[0]) & (day < _SPELL[1]), 9.0, 0.0)
    jitter = 1.6 * (_noise(n, seed, 2) - 0.5)
    oat = np.round(season + diurnal + swing + spell + jitter, 1)
    return idx, oat


def _enable(oat: np.ndarray, lockout: float) -> np.ndarray:
    """The plant's outdoor-air enable: off above ``lockout``, back on below it minus the
    deadband, held in between."""
    on = np.zeros(len(oat), dtype=bool)
    state = True
    for i, t in enumerate(oat):
        if t > lockout:
            state = False
        elif t < lockout - _DEADBAND_F:
            state = True
        on[i] = state
    return on


def _hw_plant_lockout(seed: int) -> dict:
    """One CSV, the four plants stacked with a ``scenario`` column (one ingest run each)."""
    idx, oat = _lockout_weather(seed)
    n = len(idx)
    hour = np.asarray(idx.hour)
    occupied = (np.asarray(idx.dayofweek) < 5) & (hour >= 7) & (hour < 18)
    morning = (np.asarray(idx.dayofweek) < 5) & (hour >= 5) & (hour < 9)
    day = np.arange(n) / 24.0
    spell = (day >= _SPELL[0]) & (day < _SPELL[1])
    frames = []
    for k, (scenario, (lockout, override, pump_on)) in enumerate(_LOCKOUT_PLANTS.items()):
        # what calls for heat: space heating below the balance point, the morning warm-up, and
        # zones reheating overcooled air in occupied hours whenever the plant lets them
        reheat = occupied & (_noise(n, seed, 10 + k) < 0.55)
        demand = (oat < _BALANCE_F) | (morning & (oat < _BALANCE_F + 8.0)) | reheat
        enabled = _enable(oat, lockout)
        if override:
            enabled = enabled | spell  # the lockout overridden through the warm spell
        fire = enabled & demand
        pump = np.ones(n, dtype=bool) if pump_on else enabled  # the pump runs with the enable
        load = np.clip((_BALANCE_F + 10.0 - oat) / 40.0, 0.15, 1.0)
        gas = np.where(fire, np.round(80.0 + 420.0 * load, 1), 0.0)
        speed = np.where(pump, np.round(35.0 + 30.0 * load, 1), 0.0)
        hws_reset = np.clip(180.0 - 1.2 * (oat - 20.0), 120.0, 180.0)
        # the loop: at the reset temperature while firing, cooling toward the plant room when not
        hws = np.empty(n)
        temp = 75.0
        for i in range(n):
            target = hws_reset[i] if fire[i] else 75.0
            temp = target if fire[i] else temp + 0.25 * (target - temp)
            hws[i] = temp
        dt = np.where(fire, 18.0 + 8.0 * load, np.where(pump, 1.5, 0.5))
        hwr = hws - dt
        frames.append(
            pd.DataFrame(
                {
                    "Timestamp": idx.strftime("%Y-%m-%d %H:%M"),
                    "scenario": scenario,
                    "OAT": oat,
                    "BLR_FIRE": fire.astype(int),
                    "BLR_GAS_KW": gas,
                    "HWP_STS": pump.astype(int),
                    "HWP_SPD": speed,
                    "HWS_T": np.round(hws, 1),
                    "HWR_T": np.round(hwr, 1),
                }
            )
        )
    text = pd.concat(frames, ignore_index=True).to_csv(
        index=False, float_format="%.1f", lineterminator="\n"
    )
    return {"hw_plant_lockout.csv": text}


#: name -> :class:`Generator`. A synthetic catalog entry names one in ``generator.name``.
GENERATORS: dict = {
    "hw_plant_lockout": Generator(
        version=1,
        files=("hw_plant_lockout.csv",),
        build=_hw_plant_lockout,
        description=(
            "a hot-water plant (OAT, boiler firing and gas input, hot-water pump status and speed, "
            "loop supply and return temperatures), hourly for eight weeks of late spring with a "
            "warm spell, as four plants: locked out at 65 F, left enabled through the warm "
            "spell, the pump left running, and locked out at 58 F"
        ),
    ),
}


# --------------------------------------------------------------------------- fetch = generate


def generator_spec(entry) -> dict:
    """``{"name", "seed", "version"}`` of a synthetic entry (``KeyError`` for an unknown one)."""
    spec = dict(entry.generator or {})
    gen = GENERATORS[spec["name"]]
    return {"name": spec["name"], "seed": int(spec.get("seed", 0)), "version": gen.version}


def generate_files(entry, dest_dir: str) -> dict:
    """Write the entry's files into ``dest_dir`` (atomically); ``{name: path}``."""
    spec = generator_spec(entry)
    texts = GENERATORS[spec["name"]].build(spec["seed"])
    os.makedirs(dest_dir, exist_ok=True)
    out = {}
    for name, text in texts.items():
        path = os.path.join(dest_dir, *name.split("/"))
        os.makedirs(os.path.dirname(path), exist_ok=True)
        tmp = path + ".part"
        with open(tmp, "w", encoding="utf-8", newline="") as fh:
            fh.write(text)
        os.replace(tmp, path)
        out[name] = path
    return out


def _current(root: str, entry, files: list) -> list | None:
    """The present files as ``[(file, path, bytes, sha256)]`` when the manifest records them as
    generated by this generator spec; else ``None`` (generate again)."""
    from ._fetch import sha256_file

    rec = _paths.read_manifest(root).get(entry.id) or {}
    if rec.get("generator") != generator_spec(entry):
        return None
    out = []
    ddir = _paths.downloads_dir(root, entry.id)
    for f in files:
        path = os.path.join(ddir, *f["name"].split("/"))
        want = ((rec.get("files") or {}).get(f["name"]) or {}).get("sha256")
        if not os.path.isfile(path) or not want:
            return None
        digest = sha256_file(path)
        if digest != want:
            return None
        out.append((f, path, os.path.getsize(path), digest))
    return out


def ensure_generated(entry, *, subset: str | None = None, data_dir=None, progress=None):
    """Generate a synthetic entry's files into the cache unless they are already there.

    The "fetch" of a ``kind: "synthetic"`` entry: returns a
    :class:`camber.datasets._ops.FetchResult` with ``downloaded_bytes`` 0. The manifest records
    the generator spec (name, version, seed), the files' sha256 and ``source: "generated"``.
    Holds the cache lock while it writes; a read-only cache that already holds the files is
    read, never written.
    """
    from ._fetch import sha256_file
    from ._ops import FetchResult

    sname = subset or "default"
    files = entry.subset_files(sname)
    root = _paths.data_dir(data_dir)
    res = FetchResult(
        dataset_id=entry.id,
        subset=sname,
        data_dir=root,
        citation=entry.citation,
        licence=entry.licence,
    )
    have = _current(root, entry, files)
    if have is None:
        _paths.require_writable(root, entry.id, f"generating {entry.id}")
        with _paths.cache_lock(root):
            ddir = _paths.downloads_dir(root, entry.id)
            if progress is not None:
                progress(files[0]["name"] if files else entry.id, 0, None)
            written = generate_files(entry, ddir)
            manifest = _paths.read_manifest(root)
            rec = manifest.get(entry.id) or {}
            recorded = {}
            have = []
            for f in files:
                path = written[f["name"]]
                digest, n = sha256_file(path), os.path.getsize(path)
                recorded[f["name"]] = {"sha256": digest, "bytes": n, "etag": None}
                have.append((f, path, n, digest))
                if progress is not None:
                    progress(f["name"], n, n)
            rec.update(
                {
                    "licence": entry.licence,
                    "access": entry.access,
                    "fetched_at": _paths.utc_now(),
                    "source": "generated",
                    "generator": generator_spec(entry),
                    "files": recorded,
                    "subsets": sorted(set(rec.get("subsets") or []) | {sname}),
                    "camber_version": __version__,
                }
            )
            manifest[entry.id] = rec
            _paths.write_manifest(root, manifest)
        skipped = False
    else:
        skipped = True
    for f, path, n, digest in have:
        res.files.append(
            {
                "name": f["name"],
                "path": path,
                "bytes": n,
                "sha256": digest,
                "skipped": skipped,
                "resumed": False,
                "generated": True,
            }
        )
    return res


