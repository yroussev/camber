"""Render the "What it does not check" list from the gap tags.

    python -m tools.cite_eval.gaps --out FILE.md

Every ``xfail`` entry of the regression corpus (``tests/citations_corpus/*.jsonl``) carries a
``gap:<name>`` tag, and every known metamorphic violation
(``tests/citations_corpus/metamorphic_known.json``) a ``gap:<relation>:<form>:<operator>``
tag. This groups them by tag and writes one item per gap: what goes wrong (a false sentence
kept, or a true one removed), how many entries show it, the findings it comes from, and two
examples. The list is generated so that it can only say what the corpus shows; it is written to
a file for review and is not copied into the docs here.
"""

from __future__ import annotations

import argparse
import glob
import json
import os
import sys

from . import facttable, relations

CORPUS = os.path.join(facttable.REPO, "tests", "citations_corpus")


def corpus_gaps(corpus: str = CORPUS) -> dict:
    out: dict = {}
    for path in sorted(glob.glob(os.path.join(corpus, "*.jsonl"))):
        with open(path, encoding="utf-8") as fh:
            for line in fh:
                if not line.strip():
                    continue
                e = json.loads(line)
                if not e.get("xfail"):
                    continue
                g = out.setdefault(
                    e["gap"], {"n": 0, "escape": 0, "strip": 0, "findings": set(), "examples": []}
                )
                g["n"] += 1
                g["escape" if e["expected"]["draft"] == "fail" else "strip"] += 1
                if e["tags"].get("finding"):
                    g["findings"].add(e["tags"]["finding"])
                if len(g["examples"]) < 2:
                    g["examples"].append(" ".join(e["draft"].split())[:220])
    return out


def generated_gaps(known_path: str = relations.KNOWN) -> dict:
    known = relations.load_known(known_path)
    out: dict = {}
    for rel, d in sorted(known.get("relations", {}).items()):
        for _key, tag in sorted(d.items()):
            g = out.setdefault(tag, {"n": 0, "relation": rel})
            g["n"] += 1
    return out


def render(corpus: dict, generated: dict) -> str:
    lines = [
        "# What it does not check (generated)",
        "",
        "Generated by `python -m tools.cite_eval.gaps` from the gap tags of the regression corpus",
        "and the known metamorphic violations. Each item is something `check_citations` gets",
        "wrong today; the count is the number of corpus entries (or generated cases) showing it.",
        "",
        "## From the acceptance-test corpus",
        "",
    ]
    for tag, g in sorted(corpus.items(), key=lambda kv: (-kv[1]["n"], kv[0])):
        what = []
        if g["escape"]:
            what.append(f"{g['escape']} false kept")
        if g["strip"]:
            what.append(f"{g['strip']} true removed")
        src = f"; from {', '.join(sorted(g['findings']))}" if g["findings"] else ""
        lines.append(f"- **{tag[4:]}** ({', '.join(what)}{src})")
        for ex in g["examples"]:
            lines.append(f"  - `{ex}`")
    lines += ["", "## From the metamorphic relations (generated cases)", ""]
    by_rel: dict = {}
    for tag, g in generated.items():
        by_rel.setdefault(g["relation"], []).append((tag, g["n"]))
    for rel in relations.RELATIONS:
        items = sorted(by_rel.get(rel, []), key=lambda t: (-t[1], t[0]))
        if not items:
            continue
        lines.append(f"- **{rel}**: " + "; ".join(f"{t.split(':', 2)[2]} ({n})" for t, n in items))
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", required=True)
    ap.add_argument("--corpus", default=CORPUS)
    ap.add_argument("--known", default=relations.KNOWN)
    a = ap.parse_args(argv)
    text = render(corpus_gaps(a.corpus), generated_gaps(a.known))
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"wrote {a.out} ({text.count(chr(10) + '- ')} items)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
