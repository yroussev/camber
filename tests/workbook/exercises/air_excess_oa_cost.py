"""Answer key: workbook exercise ``air-excess-oa-cost`` (docs/workbook/air-excess-oa-cost.md).

The dataset is synthetic (``synthetic-ahu-excess-oa``, generated by CAMBER: 0.108, Track C2), so
the stand-in *is* the real data, as in ``air-maintenance``: :func:`standin` generates and ingests
the catalog entry itself, offline, and every expectation holds on both modes. Figures were
recorded from::

    camber datasets fetch synthetic-ahu-excess-oa
    camber datasets ingest synthetic-ahu-excess-oa --store lab_store
    camber datasets config synthetic-ahu-excess-oa --exercise air-excess-oa-cost \
        --store lab_store --out oa.json
    camber run oa.json --out oa_out
    camber report oa.json --layout rcx --out oa_rcx.html
    camber datasets score synthetic-ahu-excess-oa --store lab_store \
        --findings oa_out/findings.json

plus the ``air-excess-oa-cost--no-min`` and ``air-excess-oa-cost--design-oa`` variants and the
sensible-only estimate in Python shown on the page (CAMBER 0.108.0-dev, 2026-10-18). The excess
outside air cost is the 0.107 estimator (#195): docs/RCX-REPORT.md, "Excess outside air cost".
"""

from __future__ import annotations

import os

from _workbook import Check, Exercise, Finding, Metric, Run, Score

from camber import datasets

_DS = "synthetic-ahu-excess-oa"
_FID = "ds-synthetic-ahu-excess-oa"
_OAF, _EHL = "outdoor_air_fraction", "economizer_high_limit"
_BAD, _ECON, _NOFLOW = "AHU__excess_oa", "AHU__economizer", "AHU__excess_oa_no_flow"


def standin(store) -> None:
    """The synthetic entry itself, generated into a cache beside the store and ingested."""
    cache = os.path.join(os.path.dirname(os.path.abspath(store.root)), "synthetic-cache")
    datasets.ingest(_DS, store.root, data_dir=cache)


def _rcx(ctx, run: str = "main"):
    """The RCx report of one run (cached on the context)."""
    from camber.report import build_rcx_report

    cache = ctx.__dict__.setdefault("_excess_oa_rcx", {})
    if run not in cache:
        cache[run] = build_rcx_report(ctx.result(run))
    return cache[run]


def _costs(ctx, run: str = "main") -> dict:
    """``{(rule, equip): FaultCost}`` of a run, priced with its config's RCx loads."""
    from camber.fault_economics import cost_findings

    rep = _rcx(ctx, run)
    fs = ctx.findings(run)
    return {(f.rule, f.equip): c for f, c in zip(fs, cost_findings(fs, rep.options.loads))}


def _appendix_b(ctx, run: str = "main") -> dict:
    """Appendix B's excess-outside-air rows, ``{(equip, rule): row}``."""
    sec = next(s for s in _rcx(ctx, run).to_dict()["sections"] if s["id"] == "appendix-b")
    table = next(b for b in sec["blocks"] if b["kind"] == "table" and "Minimum OA" in b["header"])
    return {(r[0], r[1]): r for r in table["rows"]}


def _issues(ctx, run: str = "main") -> dict:
    return {i["equip"]: i for i in _rcx(ctx, run).to_dict()["issues"]}


def _three_paths(ctx) -> None:
    """Step 2: the unit's excess samples split three ways, read from the finding's ``oa_cost_*``
    metrics. Every cooling-classed hour is on the enthalpy path (both humidities are trended)."""
    m = ctx.finding(_OAF, _BAD).metrics
    assert m["oa_cost_cool_basis"] == "enthalpy", m["oa_cost_cool_basis"]
    assert m["oa_cost_heat_basis"] == "heat_valve", m["oa_cost_heat_basis"]
    assert m["oa_cost_airflow"] == "trended supply airflow", m["oa_cost_airflow"]
    assert m["oa_cost_observed_h"] == 1008.0, m["oa_cost_observed_h"]
    assert m["oa_cost_heat_unjudged_h"] == 0.0, m["oa_cost_heat_unjudged_h"]
    assert m["min_oa_source"] == "configured", m["min_oa_source"]


def _priced(ctx) -> None:
    """Step 3: the RCx report prices the unit at $731/yr: $675 of cooling electricity (4,499 kWh
    at COP 3.5) and $56 of heating gas (46.4 therms at 80 %), the 1,008 observed hours scaled to a
    year. Both rules flag it; they share one issue, priced at the larger estimate."""
    c = _costs(ctx)[(_OAF, _BAD)]
    assert c.costed and c.basis == "excess-OA->cooling+heating", c.basis
    assert (round(c.annual_cost_usd, 2), c.electricity_kwh, c.gas_therms) == (730.51, 4499.1, 46.4)
    a = c.assumptions
    assert (a["excess_cool_kbtu_yr"], a["excess_heat_kbtu_yr"]) == (53727.8, 3710.1), a
    assert (a["cool_cop"], a["boiler_efficiency"], a["annual_hours"]) == (3.5, 0.8, 8760.0), a
    ehl = _costs(ctx)[(_EHL, _BAD)]
    assert ehl.basis == "excess-OA->cooling" and round(ehl.annual_cost_usd, 2) == 645.23, ehl
    iss = _issues(ctx)[_BAD]
    assert iss["rules"] == [_EHL, _OAF] and iss["cost"] == 730.51, iss
    assert iss["cost_basis_note"].startswith("member estimates overlap; largest shown"), iss
    k = _rcx(ctx).to_dict()["kpis"]
    assert (k["annual_cost_usd"], k["n_costed"], k["n_uncosted"]) == (730.51, 1, 1), k


def _appendix(ctx) -> None:
    """Step 3: Appendix B lists the minimum and its source, the airflow, the cooling and heating
    bases with their hours and efficiencies, and the estimate."""
    rows = _appendix_b(ctx)
    assert rows[(_BAD, _OAF)][2:] == [
        "20% (configured)",
        "trended supply airflow",
        "enthalpy, 104 h, COP 3.5",
        "heat_valve, 14 h, boiler efficiency 0.8",
        "$731/yr from 1,008 observed h x 8,760/yr",
    ], rows[(_BAD, _OAF)]
    assert rows[(_BAD, _EHL)][4:] == [
        "enthalpy, 82 h, COP 3.5",
        "—",
        "$645/yr from 1,008 observed h x 8,760/yr",
    ], rows[(_BAD, _EHL)]
    assert all(e != _ECON for e, _r in rows), rows  # an ok unit has no row


def _twin_costs_nothing(ctx) -> None:
    """Step 4: the economizer spends 95 hours above its minimum, all of it free cooling, and its
    verdict is ok, so nothing is priced and it has no issue."""
    m = ctx.finding(_OAF, _ECON).metrics
    assert m["oa_cost_flagged"] is False and m["oa_cost_economizing_h"] == 95.25, m
    c = _costs(ctx)[(_OAF, _ECON)]
    assert not c.costed and c.basis == "no excess-OA verdict (nothing priced)", c.basis
    assert _ECON not in _issues(ctx), list(_issues(ctx))


def _sensible_only(ctx) -> None:
    """Step 5: the same unit priced without its humidity points, on the dry-bulb (sensible) path.
    22 of the 103.5 cooling hours have outdoor air cooler than the return air but more humid: read
    by dry bulb they are economizing, so the estimate falls from $731 to $255/yr."""
    from camber.fault_economics import cost_findings
    from camber.model.roles import Role
    from camber.rules.oafraction_rule import OutdoorAirFraction
    from camber.store import ParquetStore

    frame = ParquetStore(ctx.store).read_role_frame(facility_id=_FID, equip=_BAD)
    dry = frame.drop(columns=[Role.OUTDOOR_RH, Role.RETURN_AIR_HUMIDITY])
    f = OutdoorAirFraction(min_oa_pct=20).analyze(_BAD, dry)
    m = f.metrics
    assert m["oa_cost_cool_basis"] == "sensible (no outdoor and return humidity trended)", m
    assert (m["oa_cost_cool_h"], m["oa_cost_economizing_h"]) == (81.5, 125.25), m
    (c,) = cost_findings([f])
    assert round(c.annual_cost_usd, 2) == 255.48, c.annual_cost_usd


def _no_flow_declines(ctx) -> None:
    """Step 6: the unit read without its airflow point faults the same way, but its estimate
    declines and names the input it needs."""
    want = "uncosted — needs supply_airflow_cfm or design_oa_cfm"
    assert _issues(ctx)[_NOFLOW]["cost"] is None, _issues(ctx)[_NOFLOW]
    assert _issues(ctx)[_NOFLOW]["cost_basis_note"] == want, _issues(ctx)[_NOFLOW]
    assert _appendix_b(ctx)[(_NOFLOW, _OAF)][3] == "—"
    assert _appendix_b(ctx)[(_NOFLOW, _OAF)][6] == want


def _no_min_declines(ctx) -> None:
    """Step 7: with no declared minimum the rule judges against its generic 20 % (the verdicts do
    not move) and every estimate declines."""
    want = "needs min_oa_pct (the unit's design minimum OA; the rule's generic 20% is not priced)"
    for (rule, equip), c in _costs(ctx, "nomin").items():
        assert rule == _OAF and not c.costed and c.basis == want, (equip, c.basis)
    assert ctx.finding(_OAF, _BAD, "nomin").metrics["min_oa_source"] == "default"
    rows = _appendix_b(ctx, "nomin")
    assert rows[(_BAD, _OAF)][2] == "20% (default)", rows[(_BAD, _OAF)]
    # 0.108 (#269): the airflow source is resolved before the decline, so it still shows
    assert rows[(_BAD, _OAF)][3] == "trended supply airflow", rows[(_BAD, _OAF)]
    assert rows[(_NOFLOW, _OAF)][3] == "—", rows[(_NOFLOW, _OAF)]
    assert _rcx(ctx, "nomin").to_dict()["kpis"]["annual_cost_usd"] is None


def _design_oa(ctx) -> None:
    """Step 8: a design outdoor airflow in the config's loads prices the no-flow unit on the supply
    airflow the declared minimum implies (2,400 / 0.20 = 12,000 cfm), more than the trended
    airflow of the same unit, which averages less at part load."""
    rows = _appendix_b(ctx, "design")
    airflow = "EquipmentLoad.design_oa_cfm / min OA fraction (12,000 cfm)"
    assert rows[(_NOFLOW, _OAF)][3] == airflow, rows[(_NOFLOW, _OAF)]
    assert rows[(_NOFLOW, _OAF)][6] == "$876/yr from 1,008 observed h x 8,760/yr"
    iss = _issues(ctx, "design")
    assert iss[_NOFLOW]["cost"] == 876.37 and iss[_BAD]["cost"] == 730.51, iss
    assert _rcx(ctx, "design").to_dict()["kpis"]["annual_cost_usd"] == 1606.88


