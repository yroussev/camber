from __future__ import annotations

import os

from _workbook import Check, Exercise, Finding, Run, Score

from camber import datasets
from camber.report import build_rcx_report
from camber.rules.triage import issue_totals, zone_chain_gaps

_DS = "synthetic-g36-rcx-chains"
_ROUND = 2


def standin(store) -> None:
    """The synthetic entry itself, generated into a cache beside the store and ingested."""
    cache = os.path.join(os.path.dirname(os.path.abspath(store.root)), "synthetic-cache")
    datasets.ingest(_DS, store.root, data_dir=cache)


def _rcx(ctx, run: str = "main"):
    cache = ctx.__dict__.setdefault("_rcx_chains", {})
    if run not in cache:
        cache[run] = build_rcx_report(ctx.result(run))
    return cache[run]


def _issue(ctx, equip: str, run: str = "main"):
    found = [i for i in _rcx(ctx, run).issues if i.equip == equip]
    assert len(found) == 1, (equip, [i.equip for i in _rcx(ctx, run).issues])
    return found[0]


def _chains(ctx) -> None:
    """Three air handlers root a chain each: the warm supply air and the weak fan reach five of
    their six boxes (not the north box, which needs little air), the cold supply air two."""
    want = {
        "AHU__warm_sat": ("sat_high", "5 of 6 boxes", (1, 2, 3, 5, 6)),
        "AHU__low_static": ("static_low", "5 of 6 boxes", (1, 2, 3, 5, 6)),
        "AHU__cold_sat": ("sat_low", "2 of 6 boxes", (2, 4)),
    }
    for ahu, (chain, count, boxes) in want.items():
        (z,) = _issue(ctx, ahu).zone_links
        scen = ahu.split("__")[1]
        assert z.chain == chain and z.count() == count, (ahu, z.chain, z.count())
        assert z.boxes == tuple(f"VAV{k}__{scen}" for k in boxes), (ahu, z.boxes)
    roots = {_issue(ctx, a).root.rule for a in want}
    assert roots == {"g36_afdd", "supply_air_reset"}, roots


def _cost(ctx) -> None:
    """The cold-supply chain is costed at its largest member (VAV4's reheat, 122.99), not the
    sum of its two boxes (197.38); the report total counts it once."""
    iss = _issue(ctx, "AHU__cold_sat")
    costs = {c.equip: round(c.annual_cost_usd, _ROUND) for c in iss.member_costs if c.costed}
    assert costs == {"VAV2__cold_sat": 74.39, "VAV4__cold_sat": 122.99}, costs
    assert round(iss.cost, _ROUND) == 122.99 and "largest shown" in iss.cost_basis_note
    assert round(issue_totals(_rcx(ctx).issues)["annual_cost_usd"], _ROUND) == 122.99
    assert round(sum(costs.values()), _ROUND) == 197.38


def _separate(ctx) -> None:
    """The stuck damper is its own box's problem: its two findings are two issues on
    VAV3__one_bad_box, in no air handler's chain, and the healthy air handlers raise nothing."""
    issues = _rcx(ctx).issues
    equips = sorted(i.equip for i in issues)
    assert equips == sorted(
        ["AHU__cold_sat", "AHU__warm_sat", "AHU__low_static"] + ["VAV3__one_bad_box"] * 2
    ), equips
    linked = {b for i in issues for z in i.zone_links for b in z.boxes}
    assert "VAV3__one_bad_box" not in linked
    assert zone_chain_gaps(ctx.findings(), ctx.result().topology) == {}


def _no_topology(ctx) -> None:
    """Without the topology nothing links: 22 issues instead of 5, the two reheat boxes counted
    separately (197.38), and the 13 boxes left unlinked listed for Appendix A."""
    rep = _rcx(ctx, "no-topology")
    assert len(rep.issues) == 22 and all(not i.zone_links for i in rep.issues)
    assert round(issue_totals(rep.issues)["annual_cost_usd"], _ROUND) == 197.38
    res = ctx.result("no-topology")
    gaps = zone_chain_gaps(res.findings, res.topology)
    assert gaps["topology"] == "none" and len(gaps["boxes"]) == 13, gaps
    assert gaps["causes"] == ["duct static too low", "supply air too cold", "supply air too warm"]
    assert len(_rcx(ctx).issues) == 5


EXERCISE = Exercise(
    id="rcx-cause-chains",
    title="RCx cause chains: one air handler, many boxes",
    issue=81,
    references=("pnnl-retuning-ch5", "pnnl-retuning-ch7"),
    datasets=(_DS,),
    runs=(
        Run(dataset=_DS, config="rcx-cause-chains"),
        Run(dataset=_DS, name="no-topology", config="rcx-cause-chains--no-topology"),
    ),
    commands=(
        "camber datasets fetch synthetic-g36-rcx-chains",
        "camber datasets ingest synthetic-g36-rcx-chains --store lab_store",
        "camber datasets config synthetic-g36-rcx-chains --exercise rcx-cause-chains "
        "--store lab_store --out chains.json",
        "camber run chains.json --out chains_out",
        "camber report chains.json --layout rcx --out chains_rcx.html",
        "camber datasets score synthetic-g36-rcx-chains --store lab_store "
        "--findings chains_out/findings.json",
        "camber datasets config synthetic-g36-rcx-chains --exercise rcx-cause-chains--no-topology "
        "--store lab_store --out chains_flat.json",
        "camber report chains_flat.json --layout rcx --out chains_flat_rcx.html",
    ),
    expect=(
        # 1. the air handlers' own findings
        Finding("g36_afdd", "AHU__warm_sat", severity=("fault",)),
        Finding("g36_afdd", "AHU__low_static", severity=("fault",)),
        Finding("g36_afdd", "AHU__healthy", severity=("ok", "info")),
        Finding("supply_air_reset", "AHU__cold_sat", severity=("warn",)),
        # 2. the chains, the cost and the box that stays apart
        Check("three chains, with their box counts", _chains, quote="5 of 6 boxes"),
        Check("the chain costs its largest member", _cost, quote="122.99"),
        Check("a bad box under a healthy air handler stays apart", _separate),
        Check("without a topology nothing links", _no_topology, quote="197.38"),
        # 3. the label score
        Score("unmet_setpoint_hours", tpr=1.0, fpr=0.0),
        Score("airflow_tracking", tpr=1.0, fpr=0.0),
        Score(None, tpr=1.0, fpr=0.0, quote="16 of 16"),
    ),
    standin=standin,
)
