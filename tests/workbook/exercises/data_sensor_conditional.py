"""Answer key: workbook exercise ``data-sensor-conditional``.

Page: docs/workbook/data-sensor-conditional.md. The dataset is synthetic
(``synthetic-ahu-sensor-bias``, generated by CAMBER: 0.108, Track C3), so the stand-in *is* the
real data, as in ``air-maintenance``: :func:`standin` generates and ingests the catalog entry
itself, offline, and every expectation holds on both modes. Figures were recorded from::

    camber datasets fetch synthetic-ahu-sensor-bias
    camber datasets ingest synthetic-ahu-sensor-bias --store lab_store
    camber datasets config synthetic-ahu-sensor-bias --exercise \
        data-sensor-conditional--no-reference --store lab_store --out before.json
    camber run before.json --out before_out
    camber report before.json --layout rcx --out before_rcx.html
    camber datasets config synthetic-ahu-sensor-bias --exercise data-sensor-conditional \
        --store lab_store --out bias.json
    camber report bias.json --layout rcx --out bias_rcx.html

(CAMBER 0.108.0-dev, 2026-10-18). Re-pinned for #267: the duct loggers come in through
``report.rcx.references`` in the exercise config, not through Python on the page; the figures
are the ones the Python route gave.

No check of a single trend can see a smooth, plausible offset, so the sensor-trust layer scores
the biased sensor "trusted", like the healthy one; the conditional findings and the at-risk total
appear once the run compares each sensor with a reference.
"""

from __future__ import annotations

import os

from _workbook import Check, Exercise, Finding, Metric, Run

from camber import datasets

_DS = "synthetic-ahu-sensor-bias"
_CTRL, _RESET, _LEAK = "supply_air_control", "supply_air_reset_compliance", "leaking_valve"
_DRIFT = "sensor_drift:supply_air_temp"
_OK, _BIAS = "AHU__healthy", "AHU__sat_bias"


def standin(store) -> None:
    """The synthetic entry itself, generated into a cache beside the store and ingested."""
    cache = os.path.join(os.path.dirname(os.path.abspath(store.root)), "synthetic-cache")
    datasets.ingest(_DS, store.root, data_dir=cache)


def _rcx(ctx, run: str):
    """The RCx report of one run (cached on the context)."""
    from camber.report import build_rcx_report

    cache = ctx.__dict__.setdefault("_sensor_rcx", {})
    if run not in cache:
        cache[run] = build_rcx_report(ctx.result(run))
    return cache[run]


def _issues(rep) -> dict:
    return {(i["equip"], tuple(i["rules"])): i for i in rep.to_dict()["issues"]}


def _data_tables(rep) -> list:
    sec = next(s for s in rep.to_dict()["sections"] if s["id"] == "data")
    return [b for b in sec["blocks"] if b["kind"] == "table"]


def _trust_misses_it(ctx) -> None:
    """Step 3: the RCx report's sensor-trust table scores both supply-air sensors trusted (1.00
    on the fan-on samples): nothing in one trend gives a 3 F offset away."""
    rows = [
        r
        for b in _data_tables(_rcx(ctx, "before"))
        if b["header"][:2] == ["Equipment", "Point"]
        for r in b["rows"]
    ]
    sat = {r[0]: r[2] for r in rows if r[1] == "supply_air_temp"}
    assert sat[_OK].startswith("trusted (1.00") and sat[_BIAS].startswith("trusted (1.00"), sat


def _rcx_before(ctx) -> None:
    """Step 4: without the references every issue is firm. The two reset findings are priced at
    $10,480/yr together, the false leaking-valve fault ranks first, and nothing is at risk."""
    rep = _rcx(ctx, "before")
    k = rep.to_dict()["kpis"]
    assert (k["annual_cost_usd"], k["at_risk_usd"], k["n_conditional"]) == (10479.92, None, 0), k
    iss = _issues(rep)
    assert iss[(_BIAS, (_LEAK,))]["rank"] == 1 and iss[(_BIAS, (_LEAK,))]["cost"] is None, iss
    assert iss[(_OK, (_RESET,))]["cost"] == 5230.31, iss[(_OK, (_RESET,))]
    assert iss[(_BIAS, (_RESET,))]["cost"] == 5249.61, iss[(_BIAS, (_RESET,))]
    assert all(not i["conditional_on"] for i in iss.values()), iss
    assert not [b for b in _data_tables(rep) if "Reference" in b["header"]]


def _reference(ctx) -> None:
    """Step 5: the report's reference table: against the duct logger (384 samples over four days)
    the healthy sensor reads +0.0 F (ok), the biased one +3.0 F (warn: 2 F; fault at 5 F), drift
    not evaluated."""
    rep = _rcx(ctx, "main")
    (table,) = [b for b in _data_tables(rep) if "Reference" in b["header"]]
    assert table["rows"] == [
        [_OK, "supply_air_temp", "duct logger", "ok", "0.0", "—", "0.07", "1.0", "384"],
        [_BIAS, "supply_air_temp", "duct logger", "warn", "3.0", "—", "3.0", "1.0", "384"],
    ], table["rows"]


def _rcx_after(ctx) -> None:
    """Step 6: with the references, the biased unit's two findings that read the supply-air sensor
    become conditional on it (confidence L) and its reset estimate moves from the firm total to the
    at-risk total: $5,230 firm, $5,250 at risk. The healthy twin's identical finding stays firm."""
    rep = _rcx(ctx, "main")
    k = rep.to_dict()["kpis"]
    assert (k["annual_cost_usd"], k["at_risk_usd"], k["n_conditional"]) == (
        5230.31,
        5249.61,
        2,
    ), k
    iss = _issues(rep)
    drift = iss[(_BIAS, (_DRIFT,))]
    assert drift["severity"] == "warn" and drift["cost"] is None, drift
    assert sorted(drift["dependents"]) == [f"{_LEAK} @ {_BIAS}", f"{_RESET} @ {_BIAS}"], drift
    for rule in (_LEAK, _RESET):
        i = iss[(_BIAS, (rule,))]
        assert i["confidence"] == "L" and len(i["conditional_on"]) == 1, i
        assert i["conditional_on"][0].startswith(f"{_DRIFT} warn"), i
    healthy = iss[(_OK, (_RESET,))]
    assert healthy["confidence"] == "H" and not healthy["conditional_on"], healthy
    assert (_OK, (_DRIFT,)) not in iss  # an ok comparison is no issue
    html = rep.to_html()
    assert "A further $5,250/yr is at risk pending a sensor fix." in html
    assert "$5,250 (at risk)" in html


EXERCISE = Exercise(
    id="data-sensor-conditional",
    title="A sensor that reads 3 °F high: conditional findings and money at risk",
    issue=83,
    references=("pnnl-retuning-ch4", "pnnl-retuning-ch5", "pnnl-guide-discharge-air-temp"),
    datasets=(_DS,),
    runs=(
        Run(dataset=_DS, config="data-sensor-conditional"),
        Run(dataset=_DS, name="before", config="data-sensor-conditional--no-reference"),
    ),
    commands=(
        "camber datasets fetch synthetic-ahu-sensor-bias",
        "camber datasets ingest synthetic-ahu-sensor-bias --store lab_store",
        "camber datasets config synthetic-ahu-sensor-bias --exercise "
        "data-sensor-conditional--no-reference --store lab_store --out before.json",
        "camber run before.json --out before_out",
        "camber report before.json --layout rcx --out before_rcx.html",
        "camber datasets config synthetic-ahu-sensor-bias --exercise data-sensor-conditional "
        "--store lab_store --out bias.json",
        "camber report bias.json --layout rcx --out bias_rcx.html",
    ),
    expect=(
        # 1. the rules on the false reading (the references change no verdict)
        Finding(_CTRL, _OK, severity=("ok",), run="before"),
        Finding(_CTRL, _BIAS, severity=("ok",), run="before"),
        Metric(_CTRL, _BIAS, "off_setpoint_pct", 0.0, 0.005, run="before", quote="0%"),
        Finding(_LEAK, _BIAS, severity=("fault",), run="before"),
        Finding(_LEAK, _OK, severity=("ok",), run="before"),
        Metric(_LEAK, _BIAS, "hw_leak_pct", 86.5, 0.05, run="before", quote="86.5%"),
        Metric(_LEAK, _BIAS, "median_delta_f", 3.4, 0.05, run="before", quote="+3.4"),
        Metric(_LEAK, _OK, "median_delta_f", 0.5, 0.05, run="before", quote="+0.5"),
        Metric(_LEAK, _BIAS, "n_both_closed", 37, 0, run="before", quote="37"),
        Finding(_RESET, _OK, severity=("warn",), run="before"),
        Finding(_RESET, _BIAS, severity=("warn",), run="before"),
        Metric(_RESET, _OK, "pct_below_target", 54.2, 0.05, run="before", quote="54.2%"),
        Metric(_RESET, _BIAS, "mean_gap_f", 3.06, 0.005, run="before", quote="3.06"),
        Finding(_LEAK, _BIAS, severity=("fault",)),
        Finding(_RESET, _OK, severity=("warn",)),
        # 2. trust cannot see it
        Check("both sensors trusted", _trust_misses_it, quote="trusted (1.00"),
        # 3. the RCx report before and after the references
        Check("before the references: all firm", _rcx_before, quote="$10,480"),
        Check("the reference table", _reference, quote="+3.0"),
        Check("after the references: conditional and at risk", _rcx_after, quote="$5,250"),
    ),
    standin=standin,
)
