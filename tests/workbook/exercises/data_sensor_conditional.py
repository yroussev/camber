"""Answer key: workbook exercise ``data-sensor-conditional``.

The dataset is synthetic (``synthetic-ahu-sensor-bias``, generated by CAMBER: 0.108, Track C3), so
the stand-in *is* the real data, as in ``air-maintenance``: :func:`standin` generates and ingests
the catalog entry itself, offline, and every expectation holds on both modes. Figures were
recorded from::

    camber datasets fetch synthetic-ahu-sensor-bias
    camber datasets ingest synthetic-ahu-sensor-bias --store lab_store
    camber datasets config synthetic-ahu-sensor-bias --exercise data-sensor-conditional \
        --store lab_store --out bias.json
    camber run bias.json --out bias_out
    camber report bias.json --layout rcx --out bias_rcx.html

plus the comparison against the duct logger and the RCx report built after it, in Python as shown
on the page (CAMBER 0.108.0-dev, 2026-10-18).

No check of a single trend can see a smooth, plausible offset, so the sensor-trust layer scores
the biased sensor "trusted", like the healthy one; the conditional findings and the at-risk total
appear only once a reference comparison (``camber.sensordrift``) is added to the run.
"""

from __future__ import annotations

import os

from _workbook import Check, Exercise, Finding, Metric, Run

from camber import datasets

_DS = "synthetic-ahu-sensor-bias"
_FID = "ds-synthetic-ahu-sensor-bias"
_CTRL, _RESET, _LEAK = "supply_air_control", "supply_air_reset_compliance", "leaking_valve"
_OK, _BIAS = "AHU__healthy", "AHU__sat_bias"


def standin(store) -> None:
    """The synthetic entry itself, generated into a cache beside the store and ingested."""
    cache = os.path.join(os.path.dirname(os.path.abspath(store.root)), "synthetic-cache")
    datasets.ingest(_DS, store.root, data_dir=cache)


def _reference_findings(ctx) -> list:
    """Each unit's supply-air sensor against the duct logger in the same duct: the page's Python."""
    from camber.model.roles import Role
    from camber.sensordrift import drift_finding
    from camber.store import ParquetStore

    store = ParquetStore(ctx.store)
    out = []
    for unit in ("healthy", "sat_bias"):
        ahu = store.read_role_frame(facility_id=_FID, equip=f"AHU__{unit}")
        logger = store.read_role_frame(facility_id=_FID, equip=f"LOGGER__{unit}")
        sat = Role.SUPPLY_AIR_TEMP
        out.append(drift_finding(ahu[sat], logger[sat], f"AHU__{unit}", sat))
    return out


def _rcx(ctx, *, with_reference: bool):
    """The RCx report of the main run, without or with the logger comparisons (cached)."""
    import copy

    from camber.report import build_rcx_report

    cache = ctx.__dict__.setdefault("_sensor_rcx", {})
    if with_reference not in cache:
        run = copy.copy(ctx.result())
        run.findings = list(run.findings)
        if with_reference:
            run.findings += _reference_findings(ctx)
        cache[with_reference] = build_rcx_report(run)
    return cache[with_reference]


def _issues(rep) -> dict:
    return {(i["equip"], tuple(i["rules"])): i for i in rep.to_dict()["issues"]}


def _trust_misses_it(ctx) -> None:
    """Step 3: the RCx report's sensor-trust table scores both supply-air sensors trusted (1.00
    on the fan-on samples): nothing in one trend gives a 3 F offset away."""
    sec = next(
        s for s in _rcx(ctx, with_reference=False).to_dict()["sections"] if s["id"] == "data"
    )
    rows = [
        r
        for b in sec["blocks"]
        if b["kind"] == "table" and b["header"][:2] == ["Equipment", "Point"]
        for r in b["rows"]
    ]
    sat = {r[0]: r[2] for r in rows if r[1] == "supply_air_temp"}
    assert sat[_OK].startswith("trusted (1.00") and sat[_BIAS].startswith("trusted (1.00"), sat


def _rcx_before(ctx) -> None:
    """Step 4: before any reference, every issue is firm. The two reset findings are priced at
    $10,480/yr together, the false leaking-valve fault ranks first, and nothing is at risk."""
    rep = _rcx(ctx, with_reference=False)
    k = rep.to_dict()["kpis"]
    assert (k["annual_cost_usd"], k["at_risk_usd"], k["n_conditional"]) == (10479.92, None, 0), k
    iss = _issues(rep)
    assert iss[(_BIAS, (_LEAK,))]["rank"] == 1 and iss[(_BIAS, (_LEAK,))]["cost"] is None, iss
    assert iss[(_OK, (_RESET,))]["cost"] == 5230.31, iss[(_OK, (_RESET,))]
    assert iss[(_BIAS, (_RESET,))]["cost"] == 5249.61, iss[(_BIAS, (_RESET,))]
    assert all(not i["conditional_on"] for i in iss.values()), iss


def _reference(ctx) -> None:
    """Step 5: against the duct logger (384 samples over four days) the healthy sensor reads
    +0.0 F, the biased one +3.0 F: a warn (2 F) under the bias fault line (5 F)."""
    ok, bias = _reference_findings(ctx)
    assert ok.rule == bias.rule == "sensor_drift:supply_air_temp", (ok.rule, bias.rule)
    assert ok.severity == "ok" and ok.metrics["bias"] == 0.0, ok.metrics
    assert bias.severity == "warn" and bias.metrics["bias"] == 3.0, bias.metrics
    assert bias.metrics["n"] == 384 and bias.metrics["correlation"] == 1.0, bias.metrics
    assert "drift not evaluated" in bias.summary, bias.summary


def _rcx_after(ctx) -> None:
    """Step 6: with the comparisons in the run, the biased unit's two findings that read the
    supply-air sensor become conditional on it (confidence L) and its reset estimate moves from
    the firm total to the at-risk total: $5,230 firm, $5,250 at risk."""
    rep = _rcx(ctx, with_reference=True)
    k = rep.to_dict()["kpis"]
    assert (k["annual_cost_usd"], k["at_risk_usd"], k["n_conditional"]) == (
        5230.31,
        5249.61,
        2,
    ), k
    iss = _issues(rep)
    drift = iss[(_BIAS, ("sensor_drift:supply_air_temp",))]
    assert drift["severity"] == "warn" and drift["cost"] is None, drift
    assert sorted(drift["dependents"]) == [f"{_LEAK} @ {_BIAS}", f"{_RESET} @ {_BIAS}"], drift
    for rule in (_LEAK, _RESET):
        i = iss[(_BIAS, (rule,))]
        assert i["confidence"] == "L" and len(i["conditional_on"]) == 1, i
        assert i["conditional_on"][0].startswith("sensor_drift:supply_air_temp warn"), i
    healthy = iss[(_OK, (_RESET,))]
    assert healthy["confidence"] == "H" and not healthy["conditional_on"], healthy
    assert (_OK, ("sensor_drift:supply_air_temp",)) not in iss  # an ok comparison is no issue
    html = rep.to_html()
    assert "A further $5,250/yr is at risk pending a sensor fix." in html
    assert "$5,250 (at risk)" in html


EXERCISE = Exercise(
    id="data-sensor-conditional",
    title="A sensor that reads 3 °F high: conditional findings and money at risk",
    issue=83,
    references=("pnnl-retuning-ch4", "pnnl-retuning-ch5", "pnnl-guide-discharge-air-temp"),
    datasets=(_DS,),
    runs=(Run(dataset=_DS, config="data-sensor-conditional"),),
    commands=(
        "camber datasets fetch synthetic-ahu-sensor-bias",
        "camber datasets ingest synthetic-ahu-sensor-bias --store lab_store",
        "camber datasets config synthetic-ahu-sensor-bias --exercise data-sensor-conditional "
        "--store lab_store --out bias.json",
        "camber run bias.json --out bias_out",
        "camber report bias.json --layout rcx --out bias_rcx.html",
    ),
    expect=(
        # 1. the rules on the false reading
        Finding(_CTRL, _OK, severity=("ok",)),
        Finding(_CTRL, _BIAS, severity=("ok",)),
        Metric(_CTRL, _BIAS, "off_setpoint_pct", 0.0, 0.005, quote="0%"),
        Finding(_LEAK, _BIAS, severity=("fault",)),
        Finding(_LEAK, _OK, severity=("ok",)),
        Metric(_LEAK, _BIAS, "hw_leak_pct", 86.5, 0.05, quote="86.5%"),
        Metric(_LEAK, _BIAS, "median_delta_f", 3.4, 0.05, quote="+3.4"),
        Metric(_LEAK, _OK, "median_delta_f", 0.5, 0.05, quote="+0.5"),
        Metric(_LEAK, _BIAS, "n_both_closed", 37, 0, quote="37"),
        Finding(_RESET, _OK, severity=("warn",)),
        Finding(_RESET, _BIAS, severity=("warn",)),
        Metric(_RESET, _OK, "pct_below_g36_target", 54.2, 0.05, quote="54.2%"),
        Metric(_RESET, _BIAS, "mean_gap_f", 3.06, 0.005, quote="3.06"),
        # 2. trust cannot see it
        Check("both sensors trusted", _trust_misses_it, quote="trusted (1.00"),
        # 3. the RCx report before and after the reference
        Check("before the reference: all firm", _rcx_before, quote="$10,480"),
        Check("the logger comparison", _reference, quote="+3.0"),
        Check("after the reference: conditional and at risk", _rcx_after, quote="$5,250"),
    ),
    standin=standin,
)
