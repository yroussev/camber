"""Answer key: workbook exercise ``plant-chiller-staging`` (docs/workbook/plant-chiller-staging.md).

The dataset is synthetic (``synthetic-chw-plant-staging``, generated by CAMBER: 0.104, #137), so
the stand-in *is* the real data, as in ``plant-lockout``: :func:`standin` generates and ingests
the catalog entry itself, offline, and every expectation holds on both modes. Figures were
recorded from::

    camber datasets fetch synthetic-chw-plant-staging
    camber datasets ingest synthetic-chw-plant-staging --store lab_store
    camber datasets config synthetic-chw-plant-staging --exercise plant-chiller-staging \
        --store lab_store --out stg.json
    camber run stg.json --out stg_out
    camber datasets score synthetic-chw-plant-staging --store lab_store \
        --findings stg_out/findings.json

plus the ``plant-chiller-staging--slope05`` variant (CAMBER 0.104.0-dev, 2026-10-11).
"""

from __future__ import annotations

import os

from _workbook import Check, Exercise, Finding, Metric, Run, Score

from camber import datasets

_DS = "synthetic-chw-plant-staging"
_STG, _CW = "chiller_staging", "condenser_water_reset"
_PLANTS = ("well_staged", "short_cycling", "left_on", "fixed_cw", "high_floor")


def standin(store) -> None:
    """The synthetic entry itself, generated into a cache beside the store and ingested."""
    cache = os.path.join(os.path.dirname(os.path.abspath(store.root)), "synthetic-cache")
    datasets.ingest(_DS, store.root, data_dir=cache)


def _two_ways_to_fail(ctx) -> None:
    """The two staging faults trip different halves of the rule: PLANT__short_cycling on its
    starts (every run at the chiller's minimum, so its load factor reads 100 %), PLANT__left_on on
    its low part load (one start in three weeks)."""
    sc = ctx.finding(_STG, "PLANT__short_cycling")
    lo = ctx.finding(_STG, "PLANT__left_on")
    assert sc is not None and lo is not None
    assert sc.metrics["low_load_pct"] == 0.0 and sc.metrics["load_factor_median_pct"] == 100.0
    assert lo.metrics["starts_per_day"] < 1.0 and lo.metrics["runtime_pct"] == 100.0, lo.metrics


def _medians(ctx) -> None:
    """The condenser water each plant runs at: the reset plants in the low 70s, the high-floor
    plant at 80.0 °F, the fixed plant at 85.0 °F."""
    want = {"well_staged": 72.8, "high_floor": 80.0, "fixed_cw": 85.0}
    for plant, med in want.items():
        f = ctx.finding(_CW, f"PLANT__{plant}")
        assert f is not None, plant
        assert f.metrics["cws_median_f"] == med, (plant, f.metrics["cws_median_f"])


EXERCISE = Exercise(
    id="plant-chiller-staging",
    title="Chiller staging and condenser-water reset",
    issue=82,
    references=("pnnl-guide-plant-cooling", "pnnl-retuning-ch8"),
    datasets=(_DS,),
    runs=(
        Run(dataset=_DS, config="plant-chiller-staging"),
        Run(dataset=_DS, name="strict", config="plant-chiller-staging--slope05"),
    ),
    commands=(
        "camber datasets fetch synthetic-chw-plant-staging",
        "camber datasets ingest synthetic-chw-plant-staging --store lab_store",
        "camber datasets config synthetic-chw-plant-staging --exercise plant-chiller-staging "
        "--store lab_store --out stg.json",
        "camber run stg.json --out stg_out",
        "camber datasets score synthetic-chw-plant-staging --store lab_store "
        "--findings stg_out/findings.json",
        "camber datasets config synthetic-chw-plant-staging --exercise "
        "plant-chiller-staging--slope05 --store lab_store --out stg05.json",
        "camber run stg05.json --out stg05_out",
    ),
    expect=(
        # 1. staging: two plants fault, for different reasons
        Finding(_STG, "PLANT__well_staged", severity=("ok",)),
        Finding(_STG, "PLANT__fixed_cw", severity=("ok",)),
        Finding(_STG, "PLANT__high_floor", severity=("ok",)),
        Finding(_STG, "PLANT__short_cycling", severity=("fault",)),
        Finding(_STG, "PLANT__left_on", severity=("fault",)),
        Metric(_STG, "PLANT__short_cycling", "starts_per_day", 13.2, 0.005, quote="13.2"),
        Metric(_STG, "PLANT__well_staged", "starts_per_day", 0.71, 0.005, quote="0.71"),
        Metric(_STG, "PLANT__left_on", "low_load_pct", 66.3, 0.05, quote="66.3%"),
        Metric(_STG, "PLANT__left_on", "load_factor_median_pct", 10.8, 0.05, quote="10.8%"),
        Metric(_STG, "PLANT__well_staged", "low_load_pct", 12.9, 0.05, quote="12.9%"),
        Check("two ways to fail the staging check", _two_ways_to_fail, quote="100%"),
        # 2. condenser water: the fixed tower warns, the reset ones pass
        Finding(_CW, "PLANT__fixed_cw", severity=("warn",)),
        Finding(_CW, "PLANT__well_staged", severity=("ok",)),
        Finding(_CW, "PLANT__short_cycling", severity=("ok",)),
        Finding(_CW, "PLANT__left_on", severity=("ok",)),
        Metric(_CW, "PLANT__fixed_cw", "cws_slope_per_wetbulb", 0.071, 0.0005, quote="0.07"),
        Metric(_CW, "PLANT__well_staged", "cws_slope_per_wetbulb", 1.056, 0.0005, quote="1.06"),
        # 3. the near miss: a reset with a high floor passes
        Finding(_CW, "PLANT__high_floor", severity=("ok",)),
        Metric(_CW, "PLANT__high_floor", "cws_slope_per_wetbulb", 0.331, 0.0005, quote="0.33"),
        Check("the condenser water each plant runs at", _medians, quote="80.0 °F"),
        # 4. the label score
        Score(_STG, tpr=1.0, fpr=0.0, quote="TPR 100%"),
        Score(_CW, tpr=1.0, fpr=0.0),
        # 5. asking for a slope of 0.5: the high-floor plant warns too
        Finding(_CW, "PLANT__high_floor", severity=("warn",), run="strict"),
        Finding(_CW, "PLANT__fixed_cw", severity=("warn",), run="strict"),
        Finding(_CW, "PLANT__well_staged", severity=("ok",), run="strict"),
        Score(_CW, tpr=1.0, fpr=0.25, tol=0.001, run="strict", quote="25%"),
    ),
    standin=standin,
)
