"""Answer key: workbook exercise ``plant-chiller-multi`` (docs/workbook/plant-chiller-multi.md).

The dataset is synthetic (``synthetic-chw-plant-multi``, generated by CAMBER: 0.105, #145), so
the stand-in *is* the real data, as in ``plant-chiller-staging``: :func:`standin` generates and
ingests the catalog entry itself, offline, and every expectation holds on both modes. Figures were
recorded from::

    camber datasets fetch synthetic-chw-plant-multi
    camber datasets ingest synthetic-chw-plant-multi --store lab_store
    camber datasets config synthetic-chw-plant-multi --exercise plant-chiller-multi \
        --store lab_store --out multi.json
    camber run multi.json --out multi_out
    camber datasets score synthetic-chw-plant-multi --store lab_store \
        --findings multi_out/findings.json

plus the three ``chiller_staging_fleet`` variants (CAMBER 0.105.0-dev, 2026-10-13).
"""

from __future__ import annotations

import os

from _workbook import Check, Exercise, Finding, Metric, Run, Score

from camber import datasets

_DS = "synthetic-chw-plant-multi"
_FLEET, _TRACK = "chiller_staging_fleet", "chw_supply_tracking"
_APP, _TOWER = "chiller_approach_fouling", "cooling_tower_approach"
_FAN = "cooling_tower_fan_effort_drift"
_PLANTS = (
    "well_run",
    "over_staged",
    "reverse_mixing",
    "fouled_condenser",
    "tower_full_fan",
    "tower_controlled",
    "near_miss",
)


def standin(store) -> None:
    """The synthetic entry itself, generated into a cache beside the store and ingested."""
    cache = os.path.join(os.path.dirname(os.path.abspath(store.root)), "synthetic-cache")
    datasets.ingest(_DS, store.root, data_dir=cache)


def _pooled_fleet(ctx) -> None:
    """Over the whole facility the fleet rule pools 21 'chillers' on one clock -- the 14 chillers
    of seven plants plus the seven secondary loops, whose pump power reads as a chiller's -- and
    calls every multi-chiller sample over-staged. Its finding sits on ``<fleet>``."""
    f = ctx.finding(_FLEET, "<fleet>")
    assert f is not None, "no chiller_staging_fleet finding on <fleet>"
    assert f.metrics["n_chillers"] == 21, f.metrics
    assert f.metrics["pct_overstaged"] == 100.0, f.metrics


def _fleet_counts_two(ctx) -> None:
    """Filtered to one plant, the fleet is that plant's two chillers."""
    for run in ("well_run", "over_staged", "near_miss"):
        f = ctx.finding(_FLEET, "<fleet>", run=run)
        assert f is not None and f.metrics["n_chillers"] == 2, (run, f and f.metrics)


def _chillers_hold_setpoint(ctx) -> None:
    """In the reverse-mixing plant both chillers make 44 °F; only the secondary loop runs warm."""
    for ch in ("CH1", "CH2"):
        f = ctx.finding(_TRACK, f"{ch}__reverse_mixing")
        assert f is not None and f.severity == "ok", (ch, f and f.severity)
        assert f.metrics["above_pct"] == 0.0 and f.metrics["chwst_median_f"] == 44.0, f.metrics
    loop = ctx.finding(_TRACK, "SECLOOP__reverse_mixing")
    assert loop is not None and loop.metrics["run_source"] == "power", loop and loop.metrics


def _controlled_tower_hides_in_fan(ctx) -> None:
    """The controlled fouled tower holds its approach at about design and spends five times the
    clean tower's samples at 90 % fan and above (the approach rule's judged samples)."""
    clean = ctx.finding(_TOWER, "TOWER__well_run")
    ctl = ctx.finding(_TOWER, "TOWER__tower_controlled")
    assert clean is not None and ctl is not None
    assert ctl.metrics["n_operating"] >= 5 * clean.metrics["n_operating"], (
        clean.metrics["n_operating"],
        ctl.metrics["n_operating"],
    )
    assert ctl.metrics["pct_hours_high_approach"] == 0.0, ctl.metrics


EXERCISE = Exercise(
    id="plant-chiller-multi",
    title="Two chillers, a secondary loop and a fouled tower",
    issue=82,
    references=("pnnl-guide-plant-cooling", "pnnl-retuning-ch8"),
    datasets=(_DS,),
    runs=(
        Run(dataset=_DS, config="plant-chiller-multi"),
        Run(dataset=_DS, name="well_run", config="plant-chiller-multi--well-run"),
        Run(dataset=_DS, name="over_staged", config="plant-chiller-multi--over-staged"),
        Run(dataset=_DS, name="near_miss", config="plant-chiller-multi--near-miss"),
    ),
    commands=(
        "camber datasets fetch synthetic-chw-plant-multi",
        "camber datasets ingest synthetic-chw-plant-multi --store lab_store",
        "camber datasets config synthetic-chw-plant-multi --exercise plant-chiller-multi "
        "--store lab_store --out multi.json",
        "camber run multi.json --out multi_out",
        "camber datasets score synthetic-chw-plant-multi --store lab_store "
        "--findings multi_out/findings.json",
        "camber datasets config synthetic-chw-plant-multi --exercise "
        "plant-chiller-multi--over-staged --store lab_store --out fleet_over.json",
        "camber run fleet_over.json --out fleet_over_out",
    ),
    expect=(
        # 1. the fleet rule over the whole facility: one pooled fleet
        Finding(_FLEET, "<fleet>", severity=("fault",)),
        Check("the pooled fleet", _pooled_fleet, quote="21"),
        # 2. the fleet rule on one plant at a time
        Check("one plant, two chillers", _fleet_counts_two),
        Finding(_FLEET, "<fleet>", severity=("ok",), run="well_run"),
        Finding(_FLEET, "<fleet>", severity=("warn",), run="over_staged"),
        Finding(_FLEET, "<fleet>", severity=("ok",), run="near_miss"),
        Metric(_FLEET, "<fleet>", "pct_overstaged", 4.9, 0.05, run="well_run", quote="4.9%"),
        Metric(_FLEET, "<fleet>", "pct_overstaged", 44.2, 0.05, run="over_staged", quote="44.2%"),
        Metric(
            _FLEET, "<fleet>", "rep_capacity_kw", 106.5, 0.05, run="over_staged", quote="106.5 kW"
        ),
        Metric(_FLEET, "<fleet>", "pct_overstaged", 13.2, 0.05, run="near_miss", quote="13.2%"),
        # 3. the secondary loop: reverse mixing, chillers on setpoint
        Finding(_TRACK, "SECLOOP__reverse_mixing", severity=("fault",)),
        Metric(_TRACK, "SECLOOP__reverse_mixing", "above_pct", 35.2, 0.05, quote="35.2%"),
        Metric(
            _TRACK, "SECLOOP__reverse_mixing", "median_excess_above_f", 4.1, 0.05, quote="4.1 °F"
        ),
        Metric(_TRACK, "SECLOOP__reverse_mixing", "deltaT_median_f", 3.4, 0.05, quote="3.4 °F"),
        Check("the chillers hold their setpoint", _chillers_hold_setpoint, quote="44 °F"),
        *(
            Finding(_TRACK, f"SECLOOP__{p}", severity=("ok",))
            for p in _PLANTS
            if p != "reverse_mixing"
        ),
        # 4. the condenser: chiller 1's approach
        Finding(_APP, "CH1__fouled_condenser", severity=("fault",)),
        Finding(_APP, "CH2__fouled_condenser", severity=("ok",)),
        Metric(_APP, "CH1__fouled_condenser", "cond_approach_f", 10.4, 0.05, quote="10.4 °F"),
        Metric(_APP, "CH1__fouled_condenser", "worst_approach_ratio", 2.08, 0.005, quote="2.08"),
        Metric(_APP, "CH1__well_run", "cond_approach_f", 2.8, 0.05, quote="2.8 °F"),
        # 5. the towers: approach at full fan, and fan effort
        Finding(_TOWER, "TOWER__tower_full_fan", severity=("fault",)),
        Finding(_TOWER, "TOWER__tower_controlled", severity=("ok",)),
        Finding(_TOWER, "TOWER__well_run", severity=("ok",)),
        Metric(_TOWER, "TOWER__tower_full_fan", "approach_median_f", 12.6, 0.05, quote="12.6 °F"),
        Metric(_TOWER, "TOWER__tower_controlled", "approach_median_f", 7.1, 0.05, quote="7.1 °F"),
        Metric(_TOWER, "TOWER__well_run", "n_operating", 54, 0, quote="54"),
        Metric(_TOWER, "TOWER__tower_controlled", "n_operating", 290, 0, quote="290"),
        Check("the controlled tower hides in its fan", _controlled_tower_hides_in_fan),
        Finding(_FAN, "TOWER__tower_controlled", severity=("fault",)),
        Finding(_FAN, "TOWER__tower_full_fan", severity=("fault",)),
        Metric(_FAN, "TOWER__tower_controlled", "fan_effort_drift_pct", 34.9, 0.05, quote="34.9"),
        Metric(_FAN, "TOWER__tower_full_fan", "fan_effort_drift_pct", 59.07, 0.05, quote="59.1"),
        # the false positive: two chillers' condenser water halves the tower's range
        Finding(_FAN, "TOWER__over_staged", severity=("warn",)),
        Metric(_FAN, "TOWER__over_staged", "fan_effort_drift_pct", 6.47, 0.05, quote="6.5"),
        # 6. the near miss passes everything
        Finding(_APP, "CH1__near_miss", severity=("ok",)),
        Metric(_APP, "CH1__near_miss", "worst_approach_ratio", 1.38, 0.005, quote="1.38"),
        Finding(_TOWER, "TOWER__near_miss", severity=("ok",)),
        Finding(_FAN, "TOWER__near_miss", severity=("ok",)),
        Metric(_FAN, "TOWER__near_miss", "fan_effort_drift_pct", 4.87, 0.05, quote="4.9"),
        # 7. the label score
        Score(_TRACK, tpr=1.0, fpr=0.0),
        Score(_APP, tpr=1.0, fpr=0.0),
        Score(_TOWER, tpr=0.5, fpr=0.0, quote="TPR 50%"),
        Score(_FAN, tpr=1.0, fpr=1 / 26, tol=0.001, quote="1 of 26"),
        Score(None, tpr=4 / 6, fpr=1 / 22, tol=0.001, quote="4 of 6"),
    ),
    standin=standin,
)
