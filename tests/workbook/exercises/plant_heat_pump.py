"""Answer key: workbook exercise ``plant-heat-pump`` (docs/workbook/plant-heat-pump.md).

The dataset is synthetic (``synthetic-heat-pump``, generated by CAMBER: 0.105, #147), so the
stand-in *is* the real data, as in ``plant-boiler-cycling``: :func:`standin` generates and ingests
the catalog entry itself, offline, and every expectation holds on both modes. Figures were
recorded from::

    camber datasets fetch synthetic-heat-pump
    camber datasets ingest synthetic-heat-pump --store lab_store
    camber datasets config synthetic-heat-pump --exercise plant-heat-pump \
        --store lab_store --out hp.json
    camber run hp.json --out hp_out
    camber datasets score synthetic-heat-pump --store lab_store --findings hp_out/findings.json

plus the ``plant-heat-pump--15min`` and ``plant-heat-pump--20rev`` variants (CAMBER
0.105.0-dev, 2026-10-13).
"""

