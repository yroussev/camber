_DS = "synthetic-heat-pump"
_DEFROST, _MODE, _CAP = "heatpump_defrost", "hp_mode_vs_need", "hp_capacity_shortfall"
_ROOM, _STAGE, _LOOP = "hp_room_imbalance", "compressor_staging", "source_loop_deltat"
