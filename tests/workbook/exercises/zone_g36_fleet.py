"""Answer key: workbook exercise ``zone-g36-fleet`` (docs/workbook/zone-g36-fleet.md).

The dataset is synthetic (``synthetic-g36-vav-fleet``, generated by CAMBER: 0.105, #144), so the
stand-in *is* the real data, as in ``plant-lockout``: :func:`standin` generates and ingests the
catalog entry itself, offline, and every expectation holds on both modes. Most of the rules are
fleet rules, whose one finding sits on ``<fleet>``: ``camber datasets score`` cannot score them,
so their answers are read from the finding's metrics. Figures were recorded from::

    camber datasets fetch synthetic-g36-vav-fleet
    camber datasets ingest synthetic-g36-vav-fleet --store lab_store
    camber datasets config synthetic-g36-vav-fleet --exercise zone-g36-fleet \
        --store lab_store --out g36.json
    camber run g36.json --out g36_out
    camber datasets score synthetic-g36-vav-fleet --store lab_store \
        --findings g36_out/findings.json

plus the ``zone-g36-fleet--healthy``, ``--near-miss``, ``--reheat`` and ``--heat-cool`` variants
(CAMBER 0.105.0-dev, 2026-10-13; re-recorded on CAMBER 0.106.0-dev, 2026-10-16, after #186:
the static census lists the equipment room as overloaded, the reheat rule reads the trended
occupancy and excuses the high heating loop, cohort_space_temp has a 1 °F floor; and again
after generator version 2: the boxes trend their active airflow setpoint, minimum and heating and
cooling loops, so the censuses count tier-1 and active-setpoint requests).
"""

from __future__ import annotations

import os

from _workbook import Check, Exercise, Finding, Metric, Run, Score

from camber import datasets

_DS = "synthetic-g36-vav-fleet"
_FLEET = "<fleet>"
_SAT_RE, _DSP_RE = "sat_reset_effectiveness", "static_reset_effectiveness"
_SAT_ROGUE, _DSP_ROGUE = "sat_rogue_zone_census", "static_rogue_zone_census"
_SAT_COHORT, _DSP_COHORT = "sat_cohort_starvation", "static_cohort_starvation"
_AIRFLOW, _TEMP = "cohort_airflow", "cohort_space_temp"
_REHEAT, _CENSUS = "reheat_minimization_g36", "zones_heat_cool_census"
_AHUS = (
    "healthy",
    "rogue_sat",
    "rogue_static",
    "starved",
    "not_responding",
    "reheat",
    "heat_cool",
    "near_miss",
)
_REHEAT_ZONES = ("VAV2__reheat", "VAV4__reheat") + tuple(f"VAV{k}__heat_cool" for k in range(1, 6))


def standin(store) -> None:
    """The synthetic entry itself, generated into a cache beside the store and ingested."""
    cache = os.path.join(os.path.dirname(os.path.abspath(store.root)), "synthetic-cache")
    datasets.ingest(_DS, store.root, data_dir=cache)


def _metrics(ctx, rule: str, run: str = "main") -> dict:
    f = ctx.finding(rule, _FLEET, run)
    assert f is not None, (rule, run)
    return f.metrics


def _resets(ctx) -> None:
    """Only AHU__not_responding's resets fail, and for two different reasons."""
    for ahu in _AHUS:
        for rule in (_SAT_RE, _DSP_RE):
            f = ctx.finding(rule, f"AHU__{ahu}")
            want = "warn" if ahu == "not_responding" else "ok"
            assert f is not None and f.severity == want, (rule, ahu, f)
    assert ctx.finding(_SAT_RE, "AHU__not_responding").metrics["reason"] == "stuck"
    assert ctx.finding(_DSP_RE, "AHU__not_responding").metrics["reason"] == "not_responding"
    sat = ctx.finding(_SAT_RE, "AHU__not_responding").metrics["failure_modes"]
    assert sat == ["stuck", "not_responding"], sat
    dsp = ctx.finding(_DSP_RE, "AHU__not_responding").metrics["failure_modes"]
    assert dsp == ["not_responding"], dsp


def _rogues(ctx) -> None:
    """Each census names its rogue by air handler; the static census lists the equipment room
    apart, as overloaded (short of cooling, not a starved inlet)."""
    sat = _metrics(ctx, _SAT_ROGUE)
    assert sat["grouping_provenance"] == "explicit" and sat["n_groups"] == 8, sat
    assert sat["rogue_by_group"] == {"AHU__rogue_sat": ["VAV1__rogue_sat"]}, sat["rogue_by_group"]
    assert sat["worst_zone"] == "VAV1__rogue_sat", sat["worst_zone"]
    dsp = _metrics(ctx, _DSP_ROGUE)
    assert dsp["rogue_by_group"] == {"AHU__rogue_static": ["VAV5__rogue_static"]}, dsp[
        "rogue_by_group"
    ]
    assert dsp["overloaded_zones"] == ["VAV1__rogue_sat"], dsp["overloaded_zones"]
    assert dsp["overloaded_share"] == {"VAV1__rogue_sat": 1.0}, dsp["overloaded_share"]
    assert dsp["worst_zone"] == "VAV5__rogue_static", dsp["worst_zone"]
    assert dsp["zone_request_share"]["VAV1__rogue_sat"] == 0.608, dsp["zone_request_share"]


def _cohorts(ctx) -> None:
    """The cohort rules name the starved air handlers; the summary names them all, worst
    first."""
    sat = _metrics(ctx, _SAT_COHORT)
    assert sat["starved_groups"] == ["AHU__not_responding"], sat["starved_groups"]
    assert sat["group_sustained_frac"]["AHU__starved"] == 0.085, sat["group_sustained_frac"]
    dsp = _metrics(ctx, _DSP_COHORT)
    assert dsp["starved_groups"] == ["AHU__not_responding", "AHU__starved"], dsp["starved_groups"]
    assert dsp["worst_group"] == "AHU__starved", dsp["worst_group"]
    assert dsp["group_sustained_frac"]["AHU__not_responding"] == 0.711, dsp
    summary = ctx.finding(_DSP_COHORT, _FLEET).summary
    assert summary.index("AHU__starved") < summary.index("AHU__not_responding"), summary


def _peers(ctx) -> None:
    """cohort_airflow (compared within each air handler) finds the two rogue boxes;
    cohort_space_temp (all 48 boxes at once) the equipment room and the reset that ignores its
    requests."""
    air = _metrics(ctx, _AIRFLOW)
    assert air["group_by_topology"] is True, air
    assert air["outliers"] == ["VAV1__rogue_sat", "VAV5__rogue_static"], air["outliers"]
    assert round(air["z"]["VAV5__rogue_static"], 1) == -5.7, air["z"]["VAV5__rogue_static"]
    temp = _metrics(ctx, _TEMP)
    want = ["VAV1__rogue_sat"] + [f"VAV{k}__not_responding" for k in (1, 2, 3, 5, 6)]
    assert sorted(temp["outliers"]) == sorted(want), temp["outliers"]
    assert round(temp["z"]["VAV1__rogue_sat"], 1) == 10.9, temp["z"]["VAV1__rogue_sat"]


def _reheat_faults(ctx) -> None:
    """reheat_minimization_g36 faults on the seven boxes that reheat above their minimum and on
    no other box."""
    fired = sorted(
        f.equip for f in ctx.findings() if f.rule == _REHEAT and f.severity in ("warn", "fault")
    )
    assert fired == sorted(_REHEAT_ZONES), fired


def _healthy_cohort(ctx) -> None:
    """On the healthy six alone every rule passes. cohort_space_temp does not flag the north
    zone: its mean is 0.8 °F below the six's median, a z of -7.6 against a spread (MAD) of
    0.07 °F, but under the rule's 1 °F floor."""
    m = _metrics(ctx, _TEMP, "healthy")
    assert m["outliers"] == [], m["outliers"]
    assert round(m["mad"], 2) == 0.07, m["mad"]
    assert round(m["z"]["VAV4__healthy"], 1) == -7.6, m["z"]
    for rule in (_SAT_ROGUE, _DSP_ROGUE, _SAT_COHORT, _DSP_COHORT, _AIRFLOW, _TEMP, _CENSUS):
        f = ctx.finding(rule, _FLEET, "healthy")
        assert f is not None and f.severity == "ok", (rule, f)


def _near_miss(ctx) -> None:
    """The near miss's zone 1 asks for the most and binds the most, under both bars' one."""
    m = _metrics(ctx, _SAT_ROGUE, "near-miss")
    assert m["rogues"] == [], m["rogues"]
    assert m["zone_binding_frac"]["VAV1__near_miss"] == 0.454, m["zone_binding_frac"]
    assert m["zone_request_share"]["VAV1__near_miss"] == 0.43, m["zone_request_share"]


