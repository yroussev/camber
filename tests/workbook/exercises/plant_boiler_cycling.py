"""Answer key: workbook exercise ``plant-boiler-cycling`` (docs/workbook/plant-boiler-cycling.md).

The dataset is synthetic (``synthetic-hw-plant-cycling``, generated by CAMBER: 0.104, #137), so
the stand-in *is* the real data, as in ``plant-lockout``: :func:`standin` generates and ingests
the catalog entry itself, offline, and every expectation holds on both modes. Figures were
recorded from::

    camber datasets fetch synthetic-hw-plant-cycling
    camber datasets ingest synthetic-hw-plant-cycling --store lab_store
    camber datasets config synthetic-hw-plant-cycling --exercise plant-boiler-cycling \
        --store lab_store --out cyc.json
    camber run cyc.json --out cyc_out
    camber datasets score synthetic-hw-plant-cycling --store lab_store \
        --findings cyc_out/findings.json

plus the ``plant-boiler-cycling--hourly`` and ``plant-boiler-cycling--10starts`` variants (CAMBER
0.104.0-dev, 2026-10-11).
"""

from __future__ import annotations

import os

from _workbook import Check, Exercise, Finding, Metric, Run, Score

from camber import datasets

_DS = "synthetic-hw-plant-cycling"
_CYCLE, _DT, _PUMP = "boiler_short_cycle", "hw_plant_deltat", "hw_pump_dp_reset"


def standin(store) -> None:
    """The synthetic entry itself, generated into a cache beside the store and ingested."""
    cache = os.path.join(os.path.dirname(os.path.abspath(store.root)), "synthetic-cache")
    datasets.ingest(_DS, store.root, data_dir=cache)


def _hourly_count_is_a_floor(ctx) -> None:
    """Resampled to an hour, the short-cycling boiler's firing status is the hour's duty: 0.25 in
    most hours. The rule counts the fewest starts those duties allow, one per firing hour, so the
    count is a floor; the runtime is the true share of time firing, and the finding says the
    trend is coarser than the 15 minutes the count needs (0.104, #143)."""
    f = ctx.finding(_CYCLE, "PLANT__short_cycling", "hourly")
    assert f is not None, "no hourly finding on PLANT__short_cycling"
    m = f.metrics
    assert m["n_starts"] == 234 and m["runtime_pct"] == 23.6, m
    assert m["interval_min"] == 60.0, m
    assert any("floor" in c for c in f.caveats), f.caveats
    cfg = ctx.config("hourly")
    assert cfg["resample"] == "1h", cfg["resample"]


def _the_pump_and_the_loop(ctx) -> None:
    """On PLANT__low_delta_t the pump runs flat out on a flat DP setpoint; on the three
    two-way-valve plants the DP setpoint is reset and the pump runs at about half speed."""
    f = ctx.finding(_PUMP, "PLANT__low_delta_t")
    assert f is not None, "no pump finding on PLANT__low_delta_t"
    assert f.metrics["dp_sp_reset_present"] is False, f.metrics
    assert f.metrics["median_speed_pct"] == 95.0, f.metrics
    for plant in ("well_tuned", "short_cycling", "marginal"):
        g = ctx.finding(_PUMP, f"PLANT__{plant}")
        assert g is not None and g.metrics["dp_sp_reset_present"] is True, plant
        assert 50.0 <= g.metrics["median_speed_pct"] <= 54.0, (plant, g.metrics)


EXERCISE = Exercise(
    id="plant-boiler-cycling",
    title="Boiler short-cycling and low hot-water delta-T",
    issue=82,
    references=("pnnl-guide-plant-heating", "pnnl-retuning-ch8"),
    datasets=(_DS,),
    runs=(
        Run(dataset=_DS, config="plant-boiler-cycling"),
        Run(dataset=_DS, name="hourly", config="plant-boiler-cycling--hourly"),
        Run(dataset=_DS, name="limit10", config="plant-boiler-cycling--10starts"),
    ),
    commands=(
        "camber datasets fetch synthetic-hw-plant-cycling",
        "camber datasets ingest synthetic-hw-plant-cycling --store lab_store",
        "camber datasets config synthetic-hw-plant-cycling --exercise plant-boiler-cycling "
        "--store lab_store --out cyc.json",
        "camber run cyc.json --out cyc_out",
        "camber datasets score synthetic-hw-plant-cycling --store lab_store "
        "--findings cyc_out/findings.json",
        "camber datasets config synthetic-hw-plant-cycling --exercise "
        "plant-boiler-cycling--hourly --store lab_store --out cyc1h.json",
        "camber run cyc1h.json --out cyc1h_out",
        "camber datasets config synthetic-hw-plant-cycling --exercise "
        "plant-boiler-cycling--10starts --store lab_store --out cyc10.json",
        "camber run cyc10.json --out cyc10_out",
    ),
    expect=(
        # 1. the starts: one plant faults, one warns, two pass
        Finding(_CYCLE, "PLANT__well_tuned", severity=("ok",)),
        Finding(_CYCLE, "PLANT__low_delta_t", severity=("ok",)),
        Finding(_CYCLE, "PLANT__short_cycling", severity=("fault",)),
        Finding(_CYCLE, "PLANT__marginal", severity=("warn",)),
        Metric(_CYCLE, "PLANT__short_cycling", "starts_per_day", 20.2, 0.005, quote="20.2"),
        Metric(_CYCLE, "PLANT__short_cycling", "runtime_pct", 23.6, 0.05, quote="23.6%"),
        Metric(_CYCLE, "PLANT__marginal", "starts_per_day", 8.15, 0.005, quote="8.15"),
        Metric(_CYCLE, "PLANT__well_tuned", "n_starts", 1, 0, quote="one start"),
        # 2. the loop and the pump
        Finding(_DT, "PLANT__low_delta_t", severity=("fault",)),
        Finding(_PUMP, "PLANT__low_delta_t", severity=("fault",)),
        Finding(_DT, "PLANT__well_tuned", severity=("ok",)),
        Finding(_DT, "PLANT__short_cycling", severity=("ok",)),
        Finding(_DT, "PLANT__marginal", severity=("ok",)),
        Finding(_PUMP, "PLANT__well_tuned", severity=("ok",)),
        Finding(_PUMP, "PLANT__short_cycling", severity=("ok",)),
        Finding(_PUMP, "PLANT__marginal", severity=("ok",)),
        Metric(_DT, "PLANT__low_delta_t", "deltaT_median_f", 8.6, 0.05, quote="8.6 °F"),
        Metric(_DT, "PLANT__well_tuned", "deltaT_median_f", 24.1, 0.05, quote="24.1 °F"),
        Metric(_PUMP, "PLANT__low_delta_t", "pct_running_near_full", 100.0, 0.0, quote="100%"),
        Check("the pump and the loop", _the_pump_and_the_loop, quote="95%"),
        # 3. the label score
        Score(_CYCLE, tpr=1.0, fpr=1 / 3, tol=0.001, quote="33%"),
        Score(_DT, tpr=1.0, fpr=0.0),
        Score(_PUMP, tpr=1.0, fpr=0.0),
        # 4. hourly: the count is a floor, the short-cycling boiler only just caught
        Finding(_CYCLE, "PLANT__short_cycling", severity=("warn",), run="hourly"),
        Finding(_CYCLE, "PLANT__marginal", severity=("warn",), run="hourly"),
        Metric(
            _CYCLE,
            "PLANT__short_cycling",
            "starts_per_day",
            11.17,
            0.005,
            run="hourly",
            quote="11.2",
        ),
        Metric(
            _CYCLE, "PLANT__marginal", "starts_per_day", 8.16, 0.005, run="hourly", quote="8.16"
        ),
        Check("an hourly count is a floor", _hourly_count_is_a_floor, quote="0.25"),
        Score(_CYCLE, tpr=1.0, fpr=1 / 3, tol=0.001, run="hourly"),
        # 5. a 10-starts limit: the marginal boiler passes, the short-cycling one still faults
        Finding(_CYCLE, "PLANT__marginal", severity=("ok",), run="limit10"),
        Finding(_CYCLE, "PLANT__short_cycling", severity=("fault",), run="limit10"),
        Score(_CYCLE, tpr=1.0, fpr=0.0, run="limit10"),
    ),
    standin=standin,
)
