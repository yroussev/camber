"""0.111 (#298): ``finding_detail`` explains exactly the finding ``rule_run`` returned, from the
same run, and every fault / warn finding has flagged-hour spans or says why it has none.

Every synthetic catalog set (generated by CAMBER, offline) is ingested into a store in a tmp
directory and run on its own run template; nothing reaches the network or a shared store.
"""

import json
import os
import sys

import numpy as np
import pandas as pd
import pytest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from camber import datasets  # noqa: E402
from camber.capabilities import CallContext, default_registry  # noqa: E402
from camber.capabilities import _cap_rule_run as rr  # noqa: E402
from camber.capabilities._common import mask_summary  # noqa: E402

SYNTHETIC = tuple(e.id for e in datasets.catalog() if e.id.startswith("synthetic-"))
HP = "synthetic-heat-pump"


@pytest.fixture(scope="module")
def sets(tmp_path_factory):
    """``{dataset id: (store, config path)}`` for every synthetic set."""
    root = tmp_path_factory.mktemp("detail298")
    store, cache = str(root / "store"), str(root / "cache")
    out = {}
    for ds in SYNTHETIC:
        datasets.ingest(ds, store, data_dir=cache)
        cfg = str(root / f"{ds}.json")
        datasets.config_template(ds, store, out=cfg)
        out[ds] = (store, cfg)
    return out


def _ctx(sets, ds, *, config=True):
    store, cfg = sets[ds]
    return CallContext(store=store, allowed_facilities={f"ds-{ds}"}, config=cfg if config else None)


def _same(a: dict, b: dict) -> bool:
    keys = ("finding_id", "rule", "equip", "severity", "summary", "caveats", "metrics")
    return all(a[k] == b[k] for k in keys)


def test_a_fighting_rooms_capacity_finding_reads_the_same_in_both(sets):
    """The reported case: rule_run defers WSHP__window_side / door_side to the room fight; the
    detail of the same id now says so too, with or without the room rule asked for."""
    reg, ctx, fid = default_registry(), _ctx(sets, HP), f"ds-{HP}"
    for args in ({}, {"rules": ["hp_capacity_shortfall", "hp_room_imbalance"]}):
        run = reg.call("rule_run", {"facility_id": fid, **args}, ctx).data
        by = {f["finding_id"]: f for f in run["findings"]}
        for unit in ("WSHP__window_side", "WSHP__door_side"):
            want = f"hp_capacity_shortfall@{unit}"
            assert by[want]["metrics"]["verdict"] == "room_fight"
            d = reg.call("finding_detail", {"facility_id": fid, "finding_id": want, **args}, ctx)
            got = d.data["finding"]
            assert _same({**got, "fact": None}, {**by[want], "fact": None}), (got, by[want])
            assert d.data["metrics"]["deferred_to"] == "hp_room_imbalance"
            assert d.data["violations"]["hours"] > 0


@pytest.mark.parametrize("ds", SYNTHETIC)
def test_every_fault_and_warn_finding_matches_and_has_spans_or_a_reason(sets, ds, monkeypatch):
    """For every fault / warn finding rule_run lists, finding_detail returns the same rule,
    severity, summary and metrics, and either contiguous spans or a violations_note.

    The run is memoised on its exact config, so each detail call reuses rule_run's run -- and a
    detail call that built any other config than rule_run's would miss the cache and fail."""
    runs: dict = {}
    real = rr.run

    def once(ctx, config, base_dir):
        key = json.dumps(config, sort_keys=True, default=str)
        if key not in runs:
            assert not runs, "finding_detail built a different run config from rule_run's"
            runs[key] = real(ctx, config, base_dir)
        return runs[key]

    monkeypatch.setattr(rr, "run", once)
    reg, ctx, fid = default_registry(), _ctx(sets, ds), f"ds-{ds}"
    findings = reg.call("rule_run", {"facility_id": fid}, ctx).data["findings"]
    flagged = [f for f in findings if f["severity"] in ("fault", "warn")]
    assert flagged, ds
    for f in flagged:
        d = reg.call("finding_detail", {"facility_id": fid, "finding_id": f["finding_id"]}, ctx)
        got = d.data["finding"]
        assert _same(got, f), (ds, f["finding_id"])
        assert got["metrics"].get("verdict") == f["metrics"].get("verdict")
        viol, note = d.data["violations"], d.data["violations_note"]
        if viol is None:
            assert note and len(note) > 40, (ds, f["finding_id"])
            continue
        assert note is None and viol["samples"] > 0 and viol["spans"], (ds, f["finding_id"])
        assert 0 < viol["share"] <= 1 and viol["samples"] <= viol["judged_samples"]
        for s in viol["spans"]:
            assert s["start"] <= s["end"] and s["hours"] > 0


def test_only_fleet_findings_and_shape_judgements_go_without_spans(sets):
    """Spans are missing only where no one unit's hours exist (a fleet finding) or the rule says
    why (``no_spans_reason``): not for the plant, heat-pump and AHU rules that count hours."""
    reg = default_registry()
    missing = set()
    for ds in ("synthetic-hw-plant-cycling", "synthetic-ahu-maintenance", HP):
        ctx, fid = _ctx(sets, ds), f"ds-{ds}"
        for f in reg.call("rule_run", {"facility_id": fid}, ctx).data["findings"]:
            if f["severity"] not in ("fault", "warn"):
                continue
            d = reg.call("finding_detail", {"facility_id": fid, "finding_id": f["finding_id"]}, ctx)
            if d.data["violations"] is None:
                missing.add(f["rule"])
                assert "fleet finding" in d.data["violations_note"]
    assert missing == {"hp_room_imbalance"}


def test_event_rules_report_events_apart_from_hours(sets):
    """boiler_short_cycle's hours are the firing on short-cycling days, its starts counted apart
    (#298: the RCx issue read starts x the interval as hours)."""
    reg, ds = default_registry(), "synthetic-hw-plant-cycling"
    ctx, fid = _ctx(sets, ds), f"ds-{ds}"
    d = reg.call(
        "finding_detail",
        {"facility_id": fid, "finding_id": "boiler_short_cycle@PLANT__short_cycling"},
        ctx,
    )
    v = d.data["violations"]
    assert v["events"] > 0 and v["hours"] > v["events"] * 0.25
    assert "counted event(s)" in d.text
    issues = reg.call("rcx_report", {"facility_id": fid}, ctx).data["issues"]
    boiler = next(i for i in issues if i["equip"] == "PLANT__short_cycling")
    assert boiler["hours"] == pytest.approx(v["hours"])


