def test_an_unset_parameter_shows_the_value_the_rule_used(sets, monkeypatch):
    """No run config: outdoor_air_fraction judges on its generic 20 % minimum. The parameter
    reads 20 (the fallback), and the excess energy the cost estimator declines to price without
    min_oa_pct is not carried as a figure. (The dataset's packaged template, which a facility
    with no config otherwise runs with since #296, is switched off here.)"""
    from camber.capabilities import _common

    monkeypatch.setattr(_common, "dataset_template", lambda ctx, fid: (None, None))
    reg, ds = default_registry(), "synthetic-ahu-excess-oa"
    ctx, fid = _ctx(sets, ds, config=False), f"ds-{ds}"
    d = reg.call(
        "finding_detail",
        {"facility_id": fid, "finding_id": "outdoor_air_fraction@AHU__excess_oa"},
        ctx,
    )
    p = next(p for p in d.data["parameters"] if p["name"] == "min_oa_pct")
    assert p["value"] == 20.0 and p["default"] is None and p["fallback"] is True
    assert "min_oa_pct = 20.0 (not set: the rule's built-in fallback)" in d.text
    m = d.data["metrics"]
    assert m["min_oa_source"] == "default"
    assert m["oa_cost_excess_cool_kbtu"] is None and m["oa_cost_excess_cool_btu_per_cfm"] is None
    assert "of the window" not in d.text and "judged occupied fan-on samples" in d.text


def test_spans_break_where_the_masks_samples_are_apart():
    """A mask over occupied hours only: Monday 16:00-17:00 and Tuesday 08:00-09:00 are two spans,
    not one from Monday to Tuesday; share is of the samples the mask covers."""
    idx = pd.DatetimeIndex(
        ["2025-06-02 15:00", "2025-06-02 16:00", "2025-06-02 17:00"]
        + ["2025-06-03 08:00", "2025-06-03 09:00", "2025-06-03 10:00"]
    )
    m = pd.Series([False, True, True, True, True, False], index=idx)
    s = mask_summary(m)
    assert s["n_spans"] == 2 and s["hours"] == 4.0
    assert [(x["start"], x["end"], x["hours"]) for x in s["spans"]] == [
        ("2025-06-02T16:00:00", "2025-06-02T17:00:00", 2.0),
        ("2025-06-03T08:00:00", "2025-06-03T09:00:00", 2.0),
    ]
    assert s["judged_samples"] == 6 and s["share"] == round(4 / 6, 4)
    e = mask_summary(m, events=pd.Series(np.array([0, 1, 0, 1, 0, 0], dtype=bool), index=idx))
    assert e["events"] == 2
